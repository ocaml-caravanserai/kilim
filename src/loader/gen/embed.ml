(* The generator of the loader text (docs/design.html, "The loader").

   embed loader.js loader.csp loader_text.ml loader.txt

   It removes the comment lines, the leading spaces and the empty lines of
   loader.js. The result is the loader text: the same bytes in each part of each
   page, and in the loader.js file. It refuses a text that is not ASCII, or that
   has "//", "/*", "</" or "<!--": an inline script ends at "</", and the strip
   knows only whole-line comments. It writes the text to loader.txt, and the
   module Loader_text with the text and the CSP source expression of the
   committed loader.csp. The rule in src/loader/dune compares loader.csp with
   the SHA-256 of loader.txt. *)

let fail fmt =
  Printf.ksprintf
    (fun s ->
      prerr_endline ("embed: " ^ s) ;
      exit 1 )
    fmt

let read f = In_channel.with_open_bin f In_channel.input_all

let is_space c = c = ' ' || c = '\t'

let strip src =
  String.split_on_char '\n' src
  |> List.filter_map (fun line ->
      let n = String.length line in
      let i = ref 0 in
      while !i < n && is_space line.[!i] do
        incr i
      done ;
      let l = String.sub line !i (n - !i) in
      if l = "" || String.starts_with ~prefix:"//" l then None else Some l )
  |> String.concat "\n"

let contains s sub =
  let n = String.length s and m = String.length sub in
  let rec go i = i + m <= n && (String.sub s i m = sub || go (i + 1)) in
  go 0

let check text =
  String.iteri
    (fun i c ->
      if Char.code c > 127 then fail "a byte that is not ASCII at %d" i )
    text ;
  List.iter
    (fun bad -> if contains text bad then fail "the text has %S" bad)
    ["//"; "/*"; "</"; "<!--"]

(* The first line of loader.csp: 'sha256-' and 44 base64 characters, then '. *)
let csp_of file =
  let line =
    match String.split_on_char '\n' (read file) with l :: _ -> l | [] -> ""
  in
  let b64 c =
    (c >= 'A' && c <= 'Z')
    || (c >= 'a' && c <= 'z')
    || (c >= '0' && c <= '9')
    || c = '+' || c = '/' || c = '='
  in
  let prefix = "'sha256-" in
  let p = String.length prefix in
  if
    String.length line = p + 45
    && String.starts_with ~prefix line
    && line.[p + 44] = '\''
    && String.for_all b64 (String.sub line p 44)
  then line
  else fail "%s: not a sha256 source expression: %S" file line

let () =
  match Sys.argv with
  | [|_; js; csp; ml; txt|] ->
      let text = strip (read js) in
      check text ;
      let csp = csp_of csp in
      Out_channel.with_open_bin txt (fun oc -> output_string oc text) ;
      Out_channel.with_open_bin ml (fun oc ->
          Printf.fprintf oc
            "(* Generated by gen/embed.ml from loader.js and loader.csp. *)\n\n\
             let text = \"%s\"\n\n\
             let csp = \"%s\"\n"
            (String.escaped text) (String.escaped csp) )
  | _ ->
      fail "usage: embed loader.js loader.csp loader_text.ml loader.txt"
